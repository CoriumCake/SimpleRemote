package com.simpleremote.data

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

class DeviceCodesTest {
    private val json = Json { ignoreUnknownKeys = true }
    private val dir = File("src/main/assets/ir")

    private fun index(name: String): List<DeviceEntry> =
        File(dir, name).takeIf { it.exists() }?.let { json.decodeFromString<List<DeviceEntry>>(it.readText()) }.orEmpty()

    @Test
    fun flipperIndexIsConsistent() {
        val idx = index("flipper_index.json")
        if (idx.isEmpty()) return // generated by tools/convert_flipper.py
        assertTrue("expected >1000 remotes, got ${idx.size}", idx.size > 1000)
        assertTrue("duplicate ids", idx.map { it.id }.toSet().size == idx.size)
        val cats = DeviceCategory.entries.map { it.id }.toSet()
        for (e in idx) {
            assertTrue("${e.id} bad category ${e.cat}", e.cat in cats && e.cat != "ac")
            assertTrue("${e.id} missing file", File(dir, "r/${e.id}.json").exists())
            assertTrue(e.brand.isNotBlank())
        }
        for (c in listOf("tv", "projector", "fan", "audio", "light"))
            assertTrue("no $c remotes", idx.any { it.cat == c })
    }

    @Test
    fun everyFlipperButtonBuildsATransmittableSignal() {
        val idx = index("flipper_index.json")
        if (idx.isEmpty()) return
        var total = 0; var bad = 0; var noTest = 0
        val badIds = sortedSetOf<String>()
        for (e in idx) {
            val root = json.parseToJsonElement(File(dir, "r/${e.id}.json").readText()) as JsonObject
            val buttons = root["b"]!!.jsonArray
            val keys = buttons.map { it.jsonArray[1].jsonPrimitive.content }.toSet()
            if (e.test.isNotEmpty() && e.test !in keys) noTest++
            for (b in buttons) {
                total++
                val sig = DeviceCatalog.flipperSignal(b.jsonArray[2].jsonArray)
                if (sig == null || sig.pattern.isEmpty() || sig.pattern.any { it <= 0 } || sig.durationMicros > 2_000_000 ||
                    sig.frequencyHz !in 20_000..60_000) { bad++; badIds += e.id }
            }
        }
        println("flipper buttons=$total bad=$bad remotes=${idx.size} badRemotes=${badIds.take(10)}")
        assertTrue("test key missing in $noTest remotes", noTest == 0)
        assertTrue("too many bad buttons: $bad of $total", bad * 1000 < total)
    }

    @Test
    fun brandStepsCollapseDuplicateCodes() {
        val idx = index("flipper_index.json")
        if (idx.isEmpty()) return
        val samsungTv = DeviceBrand("Samsung", idx.filter { it.cat == "tv" && brandKey(it.brand) == "samsung" })
        assertTrue(samsungTv.entries.size > 10)
        assertTrue("steps ${samsungTv.steps.size} should be far fewer than ${samsungTv.entries.size}",
            samsungTv.steps.size * 2 < samsungTv.entries.size)
        // the saved remote of a step is its fullest one
        samsungTv.steps.forEach { s -> assertTrue(s.first().n == s.maxOf { it.n }) }
    }

    @Test
    fun irextIndexIsConsistent() {
        val idx = index("irext_index.json")
        if (idx.isEmpty()) return // generated by tools/convert_irext_devices.py
        assertTrue("expected >2000 remotes, got ${idx.size}", idx.size > 2000)
        assertTrue("duplicate ids", idx.map { it.id }.toSet().size == idx.size)
        val cats = DeviceCategory.entries.map { it.id }.toSet()
        for (e in idx) {
            assertTrue("${e.id} bad category ${e.cat}", e.cat in cats && e.cat != "ac")
            assertTrue("${e.id} missing binary", File(dir, "../ir_irext/${e.file}.bin").exists())
            val names = IrextDevice.KEYS[e.ic]
            assertTrue("${e.id} unknown IRext category ${e.ic}", names != null)
            assertTrue("${e.id} has no power key", 0 in e.k && names!![0]!!.second == "power")
            assertTrue("${e.id} no keys", e.k.isNotEmpty() && e.n == e.k.size)
        }
        for (c in listOf("tv", "disc", "fan", "projector", "audio"))
            assertTrue("no IRext $c remotes", idx.count { it.cat == c } > 50)
    }
}
