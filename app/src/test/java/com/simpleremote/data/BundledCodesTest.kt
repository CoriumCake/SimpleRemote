package com.simpleremote.data

import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/** Runs every bundled SmartIR code through the decoder and state lookup, and sanity-checks the IRext index. */
class BundledCodesTest {
    private val json = Json { ignoreUnknownKeys = true }
    private val dir = File("src/main/assets/ac")
    private val irextDir = File("src/main/assets/ac_irext")

    private fun devices(): List<AcDevice> =
        listOf(dir, File("src/main/assets/ac_extra")).flatMap { d ->
            d.listFiles { f -> f.name != "index.json" && f.extension == "json" }.orEmpty().toList()
        }.map { json.decodeFromString(AcDevice.serializer(), it.readText()) }

    @Test
    fun smartirIndexMatchesFiles() {
        val index = json.decodeFromString<List<AcIndexEntry>>(File(dir, "index.json").readText())
        assertTrue("expected hundreds of remotes, got ${index.size}", index.size > 300)
        index.forEach {
            assertTrue(it.id.startsWith("smartir:"))
            assertTrue("missing ${it.file}.json", File(dir, "${it.file}.json").exists())
        }
    }

    @Test
    fun irextIndexIsConsistent() {
        val f = File(irextDir, "index.json")
        if (!f.exists()) return // generated by tools/convert_irext.py
        val index = json.decodeFromString<List<AcIndexEntry>>(f.readText())
        assertTrue("expected >1000 IRext remotes, got ${index.size}", index.size > 1000)
        val dupes = index.groupingBy { it.id }.eachCount().filterValues { it > 1 }.keys
        assertTrue("duplicate ids: ${dupes.take(5)}", dupes.isEmpty())
        for (e in index) {
            assertEquals("irext", e.source)
            assertTrue("missing ${e.file}.bin", File(irextDir, "${e.file}.bin").exists())
            val caps = e.caps!!
            assertTrue(e.modes.isNotEmpty() && e.modes.all { it in caps })
            caps.values.forEach { c -> c.temps.forEach { assertTrue(it in 16..30) } }
        }
        assertTrue("Saijo Denki must be present", index.any { brandKey(it.manufacturer) == "saijodenki" })
    }

    /** Frames themselves are checked on the host by tools/esp_probe.cpp (encode + IRrecv round-trip). */
    @Test
    fun espIndexIsConsistent() {
        val f = File("src/main/assets/ac_esp/index.json")
        if (!f.exists()) return // generated by tools/convert_esp.py
        val index = json.decodeFromString<List<AcIndexEntry>>(f.readText())
        assertTrue("expected >100 IRremoteESP8266 code sets, got ${index.size}", index.size > 100)
        val dupes = index.groupingBy { it.id }.eachCount().filterValues { it > 1 }.keys
        assertTrue("duplicate ids: ${dupes.take(5)}", dupes.isEmpty())
        for (e in index) {
            assertEquals("esp", e.source)
            assertTrue(e.id, e.protocol != null && e.protocolName != null)
            val caps = e.caps!!
            assertTrue(e.id, e.modes.isNotEmpty() && e.modes.all { it in caps })
            assertTrue(e.id, caps.values.any { it.temps.isNotEmpty() })
            caps.values.forEach { c -> c.temps.forEach { assertTrue(it in 16..30) } }
        }
        for (b in listOf("daikin", "mitsubishielectric", "gree", "panasonic", "fujitsu", "lg", "samsung", "toshiba", "haier"))
            assertTrue("$b missing", index.any { brandKey(it.manufacturer) == b })
    }

    @Test
    fun everyStateCodeDecodesAndIsTransmittable() {
        var total = 0; var failed = 0; var missing = 0
        val badDevices = sortedSetOf<String>()
        val leaders = mutableListOf<Int>()
        for (d in devices()) {
            if (d.toSignal(d.off) == null) { badDevices += d.id; failed++ }
            for (mode in d.modes) {
                val caps = d.capabilities(mode)
                for (fan in caps.fans.ifEmpty { listOf(null) })
                    for (swing in caps.swings.ifEmpty { listOf(null) })
                        for (t in caps.temps.ifEmpty { listOf(d.defaultState().temp) }) {
                            val code = d.codeFor(AcState(true, mode, fan, swing, t))
                            if (code == null) { missing++; continue }
                            total++
                            val sig = d.toSignal(code)
                            if (sig == null || sig.pattern.isEmpty() || sig.pattern.any { it <= 0 } ||
                                sig.durationMicros > 2_000_000) { failed++; badDevices += d.id; continue }
                            leaders += sig.pattern[0]
                        }
            }
        }
        val medianLeader = leaders.sorted()[leaders.size / 2]
        println("codes=$total failed=$failed missingCombos=$missing medianLeader=${medianLeader}us bad=$badDevices")
        assertTrue("median leader $medianLeader µs is implausible", medianLeader in 2_500..10_000)
        assertTrue("too many undecodable codes: $failed of $total ($badDevices)", failed * 100 < total)
    }

    @Test
    fun defaultStateIsResolvableForAlmostAllRemotes() {
        val all = devices()
        val unresolved = all.filter { d -> d.signals(d.defaultState().copy(power = true), AcAction.POWER_ON).isEmpty() }.map { it.id }
        println("default state unresolved: ${unresolved.size}/${all.size} $unresolved")
        assertTrue(unresolved.size * 20 < all.size)
    }

    @Test
    fun scanListCoversEveryFamilyOnce() {
        val f = File("src/main/assets/scan.json")
        if (!f.exists()) return
        val scan = json.decodeFromString<List<String>>(f.readText())
        val ids = json.decodeFromString<List<AcIndexEntry>>(File(dir, "index.json").readText()).map { it.id }.toMutableSet()
        for (d in listOf(irextDir, File("src/main/assets/ac_esp"), File("src/main/assets/ac_extra")))
            File(d, "index.json").takeIf { it.exists() }?.let { ids += json.decodeFromString<List<AcIndexEntry>>(it.readText()).map { e -> e.id } }
        assertEquals(scan.size, scan.toSet().size)
        assertTrue("unknown ids in scan.json", scan.all { it in ids })
        assertTrue("scan list should be short, got ${scan.size}", scan.size in 50..400)
    }

    @Test
    fun brandKeyNormalises() {
        assertEquals(brandKey("Saijo-Denki"), brandKey("saijo denki"))
        assertEquals(brandKey("DaiKin"), brandKey("Daikin"))
        assertTrue(brandKey("Mitsubishi Electric") != brandKey("Mitsubishi Heavy"))
    }

    @Test
    fun tempKeyFormatting() {
        assertEquals("24", tempKey(24.0))
        assertEquals("16.5", tempKey(16.5))
    }
}
